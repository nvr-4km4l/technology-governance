
param(
    [Parameter(Mandatory = $true)]
    [string]$ReportPath,

    [Parameter(Mandatory = $true)]
    [string]$Repository,

    [switch]$CreateIssue
)

$ErrorActionPreference = "Stop"

if (-not (Test-Path $ReportPath)) {
    throw "Framework change report not found: $ReportPath"
}

$report = Get-Content $ReportPath -Raw | ConvertFrom-Json

$changes = @(
    $report.changes | Where-Object {
        $_.status -in @("VersionChanged", "Added", "Removed")
    }
)

if ($changes.Count -eq 0) {
    Write-Host "No framework changes detected."
    exit 0
}

Write-Host "Framework changes detected: $($changes.Count)"

if ($CreateIssue -and -not $env:GH_TOKEN) {
    throw "GH_TOKEN is required for GitHub Issue creation."
}

foreach ($change in $changes) {

    $framework = [string]$change.framework
    $project = [string]$change.project
    $projectType = [string]$change.projectType
    $status = [string]$change.status
    $previousVersion = [string]$change.previousVersion
    $currentVersion = [string]$change.currentVersion

    $title = "[Technology Governance] Framework ${status}: $framework ($project) [$previousVersion -> $currentVersion]"

    $body = @"
## Framework Change Detected

**Project Type:** $projectType

**Project:** $project

**Framework:** $framework

**Change Type:** $status

**Previous Version:** $previousVersion

**Current Version:** $currentVersion

## Recommended Actions

1. Review the framework version change.
2. Verify compatibility with the application.
3. Run relevant build and automated tests.
4. Review lifecycle and security implications.

---
Automatically generated by Technology Governance.
"@

    Write-Host ""
    Write-Host "Framework: $framework"
    Write-Host "Project: $project"
    Write-Host "Status: $status"
    Write-Host "Previous: $previousVersion"
    Write-Host "Current: $currentVersion"

    if (-not $CreateIssue) {
        Write-Host "[DRY RUN] Would create issue: $title"
        continue
    }

    # Fetch existing open issues.
    $existingJson = gh issue list `
        --repo $Repository `
        --state open `
        --limit 1000 `
        --json title

    if ($LASTEXITCODE -ne 0) {
        throw "Failed to retrieve existing GitHub Issues."
    }

    $existingIssues = @($existingJson | ConvertFrom-Json)

    $duplicate = @(
        $existingIssues | Where-Object {
            $_.title -eq $title
        }
    ).Count -gt 0

    if ($duplicate) {
        Write-Host "Duplicate issue found. Skipping: $title"
        continue
    }

    gh issue create `
        --repo $Repository `
        --title $title `
        --body $body

    if ($LASTEXITCODE -ne 0) {
        throw "Failed to create GitHub Issue: $title"
    }

    Write-Host "GitHub Issue created successfully!"
}

Write-Host ""
Write-Host "Framework change issue processing completed."
